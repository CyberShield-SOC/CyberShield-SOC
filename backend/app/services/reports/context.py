"""Per-request context shared by every report builder: the resolved time
range, filters, timezone, and who generated the report.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from zoneinfo import ZoneInfo

from app.services.reports.components import format_timestamp
from app.services.reports.params import ReportRange


@dataclass(frozen=True)
class ReportContext:
    report_range: ReportRange
    severity: str | None
    generated_at: datetime
    actor_name: str
    tz_name: str

    @property
    def tz_label(self) -> str:
        localized = self.generated_at.astimezone(ZoneInfo(self.tz_name))
        offset = localized.strftime("%z")
        offset_label = f"{offset[:3]}:{offset[3:]}" if offset else "+00:00"
        return f"{self.tz_name} (UTC{offset_label})"

    def local(self, value: datetime) -> datetime:
        return value.astimezone(ZoneInfo(self.tz_name))

    def format(self, value: datetime) -> str:
        return format_timestamp(self.local(value), self.tz_name)


def common_metadata(ctx: ReportContext, *, time_range_label: str, data_sources: list[tuple[str, int]]) -> list[tuple[str, str]]:
    sources_label = ", ".join(f"{name} ({count:,})" for name, count in data_sources)
    filters_label = f"Severity: {ctx.severity.title()}" if ctx.severity else "Severity: All"
    return [
        ("Time range", time_range_label),
        ("Generated at", ctx.format(ctx.generated_at)),
        ("Generated by", ctx.actor_name),
        ("Filters applied", filters_label),
        ("Timezone", ctx.tz_label),
        ("Data sources", sources_label),
    ]
