"""End-to-end: every file in sample-logs/detection goes through the real
/upload pipeline (parser -> normalizer -> 28 rules -> cooldown -> storage)
and must raise exactly the detections it was written to demonstrate.

Samples are regenerated by sample-logs/detection/generate_samples.py. All
uploads in one test share the rolled-back database transaction, so
cross-upload state (baselines, heartbeats, feeds) behaves as in production.
Pre-existing dev-database history is neutralised inside that transaction so
earlier manual uploads of the same samples can't suppress or seed results.
"""

