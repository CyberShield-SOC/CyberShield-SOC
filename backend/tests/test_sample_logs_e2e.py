def test_all_samples_in_recommended_order_cover_every_group():
    """One continuous session, uploading everything as a user would."""

    configure_rosters()
    import_feed()
    fired: set[str] = set()
    for name in (
        "group-a-host-integrity.log", "group-a-normal-admin.log", "audit.log",
        "group-b-identity.log", "group-b-normal-logins.log", "group-b-geo-logins.csv",
        "group-b-dormant-part1.csv", "group-b-dormant-part2.csv",
        "group-c-firewall.log", "group-c-netflow.csv", "group-c-dns.log",
        "group-a-heartbeat.log",
    ):
        fired |= set(by_rule(upload(name)))

    assert GROUP_A | GROUP_B | GROUP_C <= fired, sorted((GROUP_A | GROUP_B | GROUP_C) - fired)
